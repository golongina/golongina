"""Regenerates www/sw.js with every file under www/ so the game is fully playable offline.
Run after adding or changing assets:  python3 tools/gen_sw.py"""
import hashlib, os
ROOT = os.path.join(os.path.dirname(__file__), '..', 'www')
files, h = [], hashlib.sha1()
for root, _, fs in os.walk(ROOT):
    for f in sorted(fs):
        rel = os.path.relpath(os.path.join(root, f), ROOT).replace(os.sep, '/')
        if rel == 'sw.js' or rel.endswith('.txt') or rel.endswith('LICENSE'):
            continue
        files.append('./' if rel == 'index.html' else './' + rel)
        h.update(open(os.path.join(root, f), 'rb').read())
files.sort()
version = h.hexdigest()[:10]
assets = ',\n  '.join(f"'{f}'" for f in files)
open(os.path.join(ROOT, 'sw.js'), 'w').write(f"""// Offline cache so the game works without a connection after the first visit.
// Generated by tools/gen_sw.py; the version changes whenever any asset changes.
const CACHE = 'metro-bocegi-{version}';
const ASSETS = [
  {assets}
];
self.addEventListener('install', e => {{ e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting())); }});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET') return;
  if (e.request.mode === 'navigate') {{ // fresh page when online, cached page when offline
    e.respondWith(fetch(e.request).catch(() => caches.match('./')));
    return;
  }}
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(hit => hit || fetch(e.request)));
}});
""")
print(len(files), 'files, cache', version)
